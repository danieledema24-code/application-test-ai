"use client";

import { useEffect } from "react";
import { useAuth } from "@/lib/auth";
import { useApi } from "@/lib/hooks";
import type { Health, Role } from "@/lib/contract";
import { Card, CardBody, CardHeader, PageHeader } from "@/components/ui";
import { SettingsTabs } from "@/components/settings/SettingsTabs";

const ROLE_LABEL: Record<Role, string> = { owner: "Owner", admin: "Admin", member: "Member", viewer: "Viewer" };

function Rows({ rows }: { rows: [string, React.ReactNode][] }) {
  return (
    <dl className="divide-y divide-line text-body">
      {rows.map(([k, v]) => (
        <div key={k} className="flex flex-wrap justify-between gap-x-4 gap-y-1 py-2.5">
          <dt className="text-fg-muted">{k}</dt>
          <dd className="text-right font-medium text-fg-strong">{v || "—"}</dd>
        </div>
      ))}
    </dl>
  );
}

/** Profile and organisation (restyle only in Phase 1; editing arrives with workspace management). */
export default function SettingsPage() {
  const { user, organisation, role, canApprove } = useAuth();
  const { data: health } = useApi<Health>("/health");
  useEffect(() => {
    document.title = "Settings · QA Analyst";
  }, []);
  return (
    <>
      <PageHeader title="Settings" description="Your profile, organisation and the people in this workspace." />
      <SettingsTabs current="profile" />
      <div className="grid max-w-4xl gap-6 md:grid-cols-2">
        <Card>
          <CardHeader title="Your profile" />
          <CardBody>
            <Rows
              rows={[
                ["Full name", user?.full_name],
                ["Email", user?.email],
                ["Role", role ? ROLE_LABEL[role] : null],
                ["Can approve quality gates", canApprove ? "Yes" : "No"],
              ]}
            />
            <p className="mt-4 text-small text-fg-muted">To change your password, sign out and use “Forgot password?”.</p>
          </CardBody>
        </Card>
        <Card>
          <CardHeader title="Organisation" />
          <CardBody>
            <Rows
              rows={[
                ["Name", organisation?.name],
                ["AI analysis", health ? (health.ai.enabled ? `Enabled${health.ai.model ? ` (${health.ai.model})` : ""}` : "Not configured: findings are generated by rules") : "…"],
                ["Discovery browser", health ? (health.browser.available ? "Available" : "Unavailable") : "…"],
              ]}
            />
          </CardBody>
        </Card>
      </div>
    </>
  );
}
