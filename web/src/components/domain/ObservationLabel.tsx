import { Bot, Eye, HelpCircle, Lightbulb, Wrench } from "lucide-react";
import type { GeneratedBy, Provenance } from "@/lib/contract";

const DEFS: Record<Provenance, { label: string; definition: string; cls: string; Icon: typeof Eye }> = {
  observed: {
    label: "Observed",
    definition: "Seen directly in the browser.",
    cls: "bg-observed-bg text-observed-fg ring-1 ring-inset ring-navy-200",
    Icon: Eye,
  },
  inferred: {
    label: "Inferred",
    definition: "Concluded from what was seen; not verified.",
    cls: "bg-inferred-bg text-inferred-fg border border-dashed border-inferred-fg",
    Icon: Lightbulb,
  },
  assumed: {
    label: "Assumed",
    definition: "Assumed without direct evidence; needs confirmation.",
    cls: "bg-overlay text-fg-muted border border-dashed border-line-input",
    Icon: HelpCircle,
  },
  unverified: {
    label: "Unverified",
    definition: "Not yet checked against evidence.",
    cls: "bg-overlay text-fg-muted border border-dashed border-line-input",
    Icon: HelpCircle,
  },
};

/** Observed / Inferred chip (design spec §8.2). Icon + text + visually hidden definition; never colour alone. */
export function ObservationLabel({ provenance, confidence, className = "" }: { provenance: Provenance | string | null | undefined; confidence?: number | null; className?: string }) {
  const def = DEFS[(provenance as Provenance) in DEFS ? (provenance as Provenance) : "unverified"];
  const Icon = def.Icon;
  return (
    <span title={def.definition} className={`inline-flex items-center gap-1 whitespace-nowrap rounded-sm px-1.5 py-0.5 text-caption font-medium ${def.cls} ${className}`}>
      <Icon className="h-3.5 w-3.5" aria-hidden />
      {def.label}
      {typeof confidence === "number" && <span className="tabular-nums">· {Math.round(confidence * 100)}%</span>}
      <span className="sr-only">: {def.definition}{typeof confidence === "number" ? ` Confidence ${Math.round(confidence * 100)} percent.` : ""}</span>
    </span>
  );
}

/** Contract: rule-generated output must say so ("Generated by rules, AI not configured"). */
export function GeneratedByLabel({ generatedBy, className = "" }: { generatedBy: GeneratedBy | string | null | undefined; className?: string }) {
  if (generatedBy === "rules")
    return (
      <span className={`inline-flex items-center gap-1 whitespace-nowrap rounded-sm bg-overlay px-1.5 py-0.5 text-caption font-medium text-fg-muted ring-1 ring-inset ring-line-strong ${className}`}>
        <Wrench className="h-3.5 w-3.5" aria-hidden />
        Generated by rules (AI not configured)
      </span>
    );
  if (generatedBy === "ai")
    return (
      <span className={`inline-flex items-center gap-1 whitespace-nowrap rounded-sm bg-overlay px-1.5 py-0.5 text-caption font-medium text-fg-muted ring-1 ring-inset ring-line-strong ${className}`}>
        <Bot className="h-3.5 w-3.5" aria-hidden />
        AI-generated
      </span>
    );
  return null;
}

/** "What do these labels mean?" explainer for view headers. */
export function LabelsHelp() {
  return (
    <details className="group text-small text-fg-muted">
      <summary className="inline-flex cursor-pointer list-none items-center gap-1 rounded-md font-medium text-navy-700 underline underline-offset-4 hover:text-navy-900">
        What do these labels mean?
      </summary>
      <dl className="mt-2 space-y-2 rounded-lg bg-surface p-3 shadow-md ring-1 ring-line">
        <div className="flex flex-wrap items-center gap-2">
          <dt>
            <ObservationLabel provenance="observed" />
          </dt>
          <dd>Seen directly in the browser.</dd>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <dt>
            <ObservationLabel provenance="inferred" />
          </dt>
          <dd>Concluded from what was seen; not verified. Discovery is read-only, so anything that would submit or change data is inferred.</dd>
        </div>
      </dl>
    </details>
  );
}
