"use client";

import { Bot, Calculator, Eye, EyeOff, Lightbulb, MessageCircleQuestion, PenLine, Wrench } from "lucide-react";
import { useEffect, useId, useRef, useState } from "react";
import type { GeneratedBy, Provenance } from "@/lib/contract";

/** Definitions shown in tooltips, sr-only text and the legend (design P2 §5.4, §16). */
export const PROVENANCE_DEFS: Record<Provenance, { label: string; definition: string; cls: string; Icon: typeof Eye }> = {
  observed: {
    label: "Observed",
    definition: "Seen directly in the application, with evidence.",
    cls: "bg-observed-bg text-observed-fg border border-solid border-observed-line",
    Icon: Eye,
  },
  inferred: {
    label: "Inferred",
    definition: "Concluded from observed evidence; not verified by testing.",
    cls: "bg-inferred-bg text-inferred-fg border border-dashed border-inferred-line",
    Icon: Lightbulb,
  },
  assumed: {
    label: "Assumed",
    definition: "Expected behaviour with no direct evidence. Confirm it with the product owner.",
    cls: "bg-assumed-bg text-assumed-fg border-2 border-dotted border-assumed-line",
    Icon: MessageCircleQuestion,
  },
  unverified: {
    label: "Unverified",
    definition: "Stated by a source such as a document, or its evidence couldn’t be resolved. Not checked against the application.",
    cls: "bg-unverified-bg text-unverified-fg border border-dashed border-unverified-line",
    Icon: EyeOff,
  },
};

function defOf(p: Provenance | string | null | undefined) {
  return PROVENANCE_DEFS[(p as Provenance) in PROVENANCE_DEFS ? (p as Provenance) : "unverified"];
}

/**
 * Provenance chip: Observed / Inferred / Assumed / Unverified. Four styles that differ by icon, border
 * style and fill, never colour alone; the definition is read after the label. Labels are code-owned and
 * never editable by people (design P2 §5.4, open question 3).
 */
export function ProvenanceLabel({ provenance, confidence, className = "" }: { provenance: Provenance | string | null | undefined; confidence?: number | null; className?: string }) {
  const def = defOf(provenance);
  const Icon = def.Icon;
  return (
    <span title={def.definition} data-provenance={def.label.toLowerCase()} className={`inline-flex items-center gap-1 whitespace-nowrap rounded-sm px-1.5 py-0.5 text-caption font-medium ${def.cls} ${className}`}>
      <Icon className="h-3.5 w-3.5" aria-hidden />
      {def.label}
      {typeof confidence === "number" && <span className="tabular-nums">· {Math.round(confidence * 100)}%</span>}
      <span className="sr-only">
        : {def.definition}
        {typeof confidence === "number" ? ` Confidence ${Math.round(confidence * 100)} percent.` : ""}
      </span>
    </span>
  );
}

/** Phase 1 name, kept as an alias (discovery views). */
export const ObservationLabel = ProvenanceLabel;

const GEN_CLS = "inline-flex items-center gap-1 whitespace-nowrap rounded-sm bg-overlay px-1.5 py-0.5 text-caption font-medium text-fg-muted ring-1 ring-inset ring-line-strong";

/** Contract: rule-generated output must say so ("Generated by rules, AI not configured"). */
export function GeneratedByLabel({ generatedBy, className = "" }: { generatedBy: GeneratedBy | "computed" | "mixed" | string | null | undefined; className?: string }) {
  if (generatedBy === "rules")
    return (
      <span className={`${GEN_CLS} ${className}`}>
        <Wrench className="h-3.5 w-3.5" aria-hidden />
        Generated by rules (AI not configured)
      </span>
    );
  if (generatedBy === "ai" || generatedBy === "mixed")
    return (
      <span className={`${GEN_CLS} ${className}`}>
        <Bot className="h-3.5 w-3.5" aria-hidden />
        AI-generated
      </span>
    );
  if (generatedBy === "human")
    return (
      <span className={`${GEN_CLS} ${className}`}>
        <PenLine className="h-3.5 w-3.5" aria-hidden />
        Written by a person
      </span>
    );
  if (generatedBy === "computed")
    return (
      <span className={`${GEN_CLS} ${className}`}>
        <Calculator className="h-3.5 w-3.5" aria-hidden />
        Computed from project data
      </span>
    );
  return null;
}

export const LEGEND_RULES = [
  "Backend behaviour (data saved, emails sent, payments processed) is never labelled Observed: discovery only sees the user interface.",
  "Approving a requirement doesn’t change its label. An approved Assumed requirement is still an assumption, now accepted by your team.",
];

/**
 * "What do these labels mean?" popover (design P2 §5.4). A real button with aria-expanded; Escape closes
 * it and returns focus to the trigger. Discovery views pass only the two labels they use.
 */
export function ProvenanceLegend({ labels = ["observed", "inferred", "assumed", "unverified"], rules = true }: { labels?: Provenance[]; rules?: boolean }) {
  const [open, setOpen] = useState(false);
  const id = useId();
  const btn = useRef<HTMLButtonElement>(null);
  const box = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        setOpen(false);
        btn.current?.focus();
      }
    };
    const onDown = (e: MouseEvent) => {
      if (box.current && !box.current.contains(e.target as Node) && !btn.current?.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener("keydown", onKey);
    document.addEventListener("mousedown", onDown);
    return () => {
      document.removeEventListener("keydown", onKey);
      document.removeEventListener("mousedown", onDown);
    };
  }, [open]);
  return (
    <div className="relative inline-block text-small">
      <button
        ref={btn}
        type="button"
        aria-expanded={open}
        aria-controls={id}
        onClick={() => setOpen((o) => !o)}
        className="inline-flex min-h-6 items-center gap-1 rounded-md font-medium text-navy-700 underline underline-offset-4 hover:text-navy-900"
      >
        What do these labels mean?
      </button>
      <div ref={box} id={id} hidden={!open} className="absolute right-0 z-40 mt-2 w-[min(28rem,85vw)] rounded-lg bg-surface p-3 text-left shadow-md ring-1 ring-line">
        <dl className="space-y-2">
          {labels.map((l) => (
            <div key={l} className="flex flex-wrap items-start gap-2">
              <dt>
                <ProvenanceLabel provenance={l} />
              </dt>
              <dd className="min-w-0 flex-1 text-fg">{PROVENANCE_DEFS[l].definition}</dd>
            </div>
          ))}
        </dl>
        {rules && (
          <ul className="mt-3 list-disc space-y-1 border-t border-line pl-5 pt-2 text-fg">
            {LEGEND_RULES.map((r) => (
              <li key={r}>{r}</li>
            ))}
          </ul>
        )}
        {!rules && <p className="mt-2 text-fg-muted">Discovery is read-only, so anything that would submit or change data is inferred.</p>}
      </div>
    </div>
  );
}

/** Phase 1 name: discovery views show only the two labels they use. */
export function LabelsHelp() {
  return <ProvenanceLegend labels={["observed", "inferred"]} rules={false} />;
}
