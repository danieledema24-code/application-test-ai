import { Lightbulb, Sparkles } from "lucide-react";
import type { FailureAnalysis } from "@/lib/types";
import { Badge } from "@/components/ui";
import { humanize } from "@/lib/format";

export function AiDraftBadge({ className = "" }: { className?: string }) {
  return (
    <Badge tone="violet" className={className} title="Generated by AI. A person must review it before it is used.">
      <Sparkles className="h-3 w-3" aria-hidden /> AI draft — review before use
    </Badge>
  );
}

export function HypothesisLabel() {
  return (
    <span className="inline-flex items-center gap-1 rounded-md bg-violet-700 px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-white">
      <Lightbulb className="h-3.5 w-3.5" aria-hidden /> Hypothesis
    </span>
  );
}

export function FailureAnalysisCard({ analysis, title = "Failure analysis" }: { analysis: FailureAnalysis; title?: string }) {
  return (
    <div className="rounded-lg border border-dashed border-violet-300 bg-violet-50/50 p-4">
      <div className="flex flex-wrap items-center gap-2">
        <HypothesisLabel />
        <h4 className="text-sm font-semibold text-slate-900">{title}</h4>
        <span className="text-xs text-slate-600">
          generated by {analysis.generatedBy === "claude" ? "AI (Claude)" : "rule-based heuristic"} · not a recorded result
        </span>
      </div>
      <dl className="mt-3 flex flex-wrap gap-x-6 gap-y-1 text-sm">
        <div className="flex gap-1.5">
          <dt className="text-slate-600">Likely category:</dt>
          <dd className="font-medium text-slate-900">{humanize(analysis.classification)}</dd>
        </div>
        <div className="flex gap-1.5">
          <dt className="text-slate-600">Confidence:</dt>
          <dd className="font-medium text-slate-900">{humanize(analysis.confidence)}</dd>
        </div>
      </dl>
      {analysis.summary && <p className="mt-2 text-sm text-slate-800">{analysis.summary}</p>}
      <div className="mt-3 grid gap-4 sm:grid-cols-2">
        {analysis.possibleCauses?.length > 0 && (
          <div>
            <p className="text-xs font-semibold uppercase tracking-wide text-slate-600">Possible causes</p>
            <ul className="mt-1 list-disc space-y-0.5 pl-5 text-sm text-slate-800">
              {analysis.possibleCauses.map((c, i) => (
                <li key={i}>{c}</li>
              ))}
            </ul>
          </div>
        )}
        {analysis.suggestedNextSteps?.length > 0 && (
          <div>
            <p className="text-xs font-semibold uppercase tracking-wide text-slate-600">Suggested next steps</p>
            <ul className="mt-1 list-disc space-y-0.5 pl-5 text-sm text-slate-800">
              {analysis.suggestedNextSteps.map((c, i) => (
                <li key={i}>{c}</li>
              ))}
            </ul>
          </div>
        )}
      </div>
    </div>
  );
}
