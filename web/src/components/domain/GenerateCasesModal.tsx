"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { Sparkles } from "lucide-react";
import { api } from "@/lib/api";
import { useApi } from "@/lib/hooks";
import { humanize } from "@/lib/format";
import type { Category, ProjectDetail, TestCase } from "@/lib/types";
import { CATEGORIES } from "@/lib/types";
import { Button, Checkbox, InlineError, Modal, SelectField, StatusPill, TextArea, TextField, useToast } from "@/components/ui";
import { AiDraftBadge } from "./AiBits";
import { ProjectSelect } from "./ProjectSelect";

type Source = "DISCOVERY" | "USER_STORY" | "REQUIREMENTS" | "DESCRIPTION" | "OPENAPI";
const SOURCES: { value: Source; label: string; placeholder: string }[] = [
  { value: "DISCOVERY", label: "Discovery results (app map)", placeholder: "Optional: focus on specific pages or flows…" },
  { value: "USER_STORY", label: "User story", placeholder: "As a customer, I want to reset my password so that…" },
  { value: "REQUIREMENTS", label: "Requirements", placeholder: "Paste requirements or acceptance criteria…" },
  { value: "DESCRIPTION", label: "Feature description", placeholder: "Describe the feature or page to test…" },
  { value: "OPENAPI", label: "OpenAPI specification", placeholder: "Paste an OpenAPI JSON or YAML document…" },
];

type GenerateResponse = { generated: TestCase[]; generatedBy: "claude" | "heuristic"; notes: string };

export function GenerateCasesModal({
  open,
  onClose,
  projectId: fixedProjectId,
  onGenerated,
}: {
  open: boolean;
  onClose: () => void;
  projectId?: string;
  onGenerated?: () => void;
}) {
  const toast = useToast();
  const [projectId, setProjectId] = useState(fixedProjectId || "");
  const [source, setSource] = useState<Source>("DESCRIPTION");
  const [text, setText] = useState("");
  const [cats, setCats] = useState<Set<Category>>(new Set(["FUNCTIONAL", "POSITIVE", "NEGATIVE"]));
  const [count, setCount] = useState(8);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<unknown>(null);
  const [result, setResult] = useState<GenerateResponse | null>(null);

  useEffect(() => {
    if (open) {
      setProjectId(fixedProjectId || "");
      setResult(null);
      setError(null);
    }
  }, [open, fixedProjectId]);

  const { data: project } = useApi<ProjectDetail>(open && projectId ? `/projects/${projectId}` : null);
  const discoveryId = project?.discovery?.status === "COMPLETED" ? project.discovery.id : undefined;
  const src = SOURCES.find((s) => s.value === source)!;

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (source === "DISCOVERY" && !discoveryId) return setError("Run a discovery on this project first, or choose another source.");
    if (source !== "DISCOVERY" && !text.trim()) return setError("Provide some input text for the generator.");
    setLoading(true);
    setError(null);
    try {
      const res = await api<GenerateResponse>(`/projects/${projectId}/test-cases/generate`, {
        body: {
          source,
          ...(text.trim() ? { text } : {}),
          ...(source === "DISCOVERY" && discoveryId ? { discoveryId } : {}),
          categories: Array.from(cats),
          count,
        },
      });
      setResult(res);
      toast(`${res.generated.length} draft test cases generated`);
      onGenerated?.();
    } catch (err) {
      setError(err);
    } finally {
      setLoading(false);
    }
  }

  return (
    <Modal
      open={open}
      onClose={onClose}
      size="lg"
      title={
        <span className="inline-flex items-center gap-2">
          <Sparkles className="h-4 w-4 text-violet-300" aria-hidden /> Generate test cases with AI
        </span>
      }
      description="Generated cases are saved as drafts. Review and approve them before use."
      footer={
        result ? (
          <Button onClick={onClose}>Done</Button>
        ) : (
          <>
            <Button variant="secondary" onClick={onClose}>
              Cancel
            </Button>
            <Button type="submit" form="gen-cases-form" loading={loading} disabled={!projectId}>
              Generate drafts
            </Button>
          </>
        )
      }
    >
      {result ? (
        <div className="space-y-3">
          <div className="flex flex-wrap items-center gap-2">
            <AiDraftBadge />
            <span className="text-xs text-fg-muted">Generated by {result.generatedBy === "claude" ? "AI (Claude)" : "rule-based heuristic"}</span>
          </div>
          {result.notes && <p className="rounded-md bg-elevated p-3 text-sm text-fg">{result.notes}</p>}
          <ul className="divide-y divide-line rounded-md border border-line">
            {result.generated.map((c) => (
              <li key={c.id} className="flex items-center gap-3 px-3 py-2 text-sm">
                <span className="font-mono text-xs text-fg-muted">{c.key}</span>
                <Link href={`/test-cases/${c.id}`} className="min-w-0 flex-1 truncate font-medium text-accent hover:underline">
                  {c.title}
                </Link>
                <span className="text-xs text-fg-muted">{humanize(c.category)}</span>
                <StatusPill status={c.status} />
              </li>
            ))}
          </ul>
          {result.generated.length === 0 && <p className="text-sm text-fg-muted">No cases were generated. Try adding more detail.</p>}
        </div>
      ) : (
        <form id="gen-cases-form" onSubmit={submit} className="space-y-4">
          {!fixedProjectId && <ProjectSelect value={projectId} onChange={setProjectId} required />}
          <SelectField label="Source" value={source} onChange={(e) => setSource(e.target.value as Source)} options={SOURCES.map((s) => ({ value: s.value, label: s.label }))} />
          {source === "DISCOVERY" && projectId && !discoveryId && (
            <p className="rounded-md bg-amber-500/10 p-2.5 text-sm text-amber-200">No completed discovery for this project yet. Start one from the Discovery tab.</p>
          )}
          <TextArea
            label={source === "DISCOVERY" ? "Additional guidance (optional)" : "Input"}
            rows={source === "OPENAPI" ? 10 : 6}
            mono={source === "OPENAPI"}
            placeholder={src.placeholder}
            value={text}
            onChange={(e) => setText(e.target.value)}
          />
          <fieldset>
            <legend className="mb-1.5 text-sm font-medium text-fg">Categories</legend>
            <div className="grid grid-cols-2 gap-2 sm:grid-cols-3">
              {CATEGORIES.map((c) => (
                <Checkbox
                  key={c}
                  label={<span className="font-normal">{humanize(c)}</span>}
                  checked={cats.has(c)}
                  onChange={() =>
                    setCats((s) => {
                      const n = new Set(s);
                      if (n.has(c)) n.delete(c);
                      else n.add(c);
                      return n;
                    })
                  }
                />
              ))}
            </div>
          </fieldset>
          <TextField label="How many cases (max)" type="number" min={1} max={50} value={count} onChange={(e) => setCount(Number(e.target.value) || 1)} wrapClassName="max-w-[10rem]" />
          <InlineError error={error} />
        </form>
      )}
    </Modal>
  );
}
