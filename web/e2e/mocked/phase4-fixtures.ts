/** Workflow with the Phase 3 stages approved and the automation stages per state. */
export function p4Workflow(q: P4State): Workflow {
  const o = overview(q);
  const done = (key: StageKey, phase: number, gate: StageState["gate"] = null): StageState => stageState(key, { phase, status: gate ? "approved" : "completed", current_version: 1, finished_at: NOW, gate });
  return {
    project_status: "active",
    stages: [
      done("intake", 1),
      done("discovery", 1, { key: "G2", policy: "recommended", status: "approved", recommendation: null }),
      done("discovery_report", 1),
      done("requirements", 2),
      done("readiness_criteria", 2, { key: "G3", policy: "required", status: "approved", recommendation: null }),
      done("test_strategy", 2, { key: "G4", policy: "required", status: "approved", recommendation: null }),
      stageState("test_design", { phase: 3, status: q.g5 ? "approved" : "awaiting_approval", current_version: 2, finished_at: NOW, gate: { key: "G5", policy: "required", status: q.g5 ? "approved" : "pending", recommendation: null } }),
      done("traceability", 3),
      stageState("automation_assessment", { status: q.assessed ? "completed" : "not_started", current_version: q.assessed ? 1 : null }),
      stageState("automation", {
        status: q.assessed ? (o.stage.status as StageState["status"]) : "not_started",
        current_version: q.assessed ? 2 : null,
        gate: q.assessed ? { key: "G6", policy: "recommended", status: o.stage.gate_status as never, recommendation: null } : null,
      }),
      ...(["execution", "failure_analysis", "defects_summary"] as StageKey[]).map((k) => stageState(k, {})),
      ...(["release_readiness", "performance"] as StageKey[]).map((k) => stageState(k, { phase: 5, available: false })),
    ],
  };
}

