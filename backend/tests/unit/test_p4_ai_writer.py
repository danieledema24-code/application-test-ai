RULE = """// TC-0019 v3 · REQ-0006 · Generated by rules (AI not configured)
import { test } from "../../fixtures";
import { ContactPage } from "../../pages/ContactPage";

test("TC-0019: Send the contact form with an empty Message", { tag: ["@TC-0019"] }, async ({ page, qa }) => {
  const contact = new ContactPage(page);
  await contact.goto();
  await contact.message.fill("");
  await contact.send.click();
  await qa.expectSubmissionBlocked(contact.form);
  await qa.expectFieldFlagged( "Message" );
});
"""

CASE = sm.CaseIn(
    lineage_id="lin-19",
    key="TC-0019",
    title="Send the contact form with an empty Message",
    version=3,
    steps=(sm.StepIn(1, "Open /contact"), sm.StepIn(2, "Press Send message", expected="Message is flagged")),
    expected_result="Submission is blocked",
)


def _ctx(llm: Any) -> Any:
    return SimpleNamespace(llm=llm, settings=SimpleNamespace(ai_max_output_tokens=4000))


def _site(label: str = "Message") -> sm.SiteModel:
    form = sm.FormInfo("contact", "Contact us", "contact", "/contact", "Send message",
                       (sm.FieldInfo("message", label, locator=f'getByLabel("{label}")'),))  # fmt: skip
    return sm.SiteModel(forms=[form], pages={"/contact": sm.PageInfo("/contact", "Contact")}, data={})


# ------------------------------------------------------------------ guard


def test_assertion_set_ignores_layout_and_comments() -> None:
    found = [a.text for a in eg.assertions(RULE)]
    assert found == ["qa.expectSubmissionBlocked(contact.form)", 'qa.expectFieldFlagged("Message")']
    restyled = RULE.replace('qa.expectFieldFlagged( "Message" )', "qa.expectFieldFlagged('Message',)").replace(
        "  await contact.goto();", "  // await qa.expectText('x');\n  await contact.goto();"
    )
    assert eg.changed(RULE, restyled) == []
    swapped = RULE.replace("expectSubmissionBlocked", "expectSubmissionAccepted")
    assert eg.changed(RULE, swapped) == [
        "added qa.expectSubmissionAccepted(contact.form)",
        "removed qa.expectSubmissionBlocked(contact.form)",
    ]


def test_expect_matcher_chains_are_assertions() -> None:
    code = 'await expect(page.getByRole("alert")).not.toHaveText(\n  "Sent",\n);\nexpect.soft(x).toBe(1);\n'
    assert [a.text for a in eg.assertions(code)] == ['expect(page.getByRole("alert")).not.toHaveText("Sent")',
                                                     "expect.soft(x).toBe(1)"]  # fmt: skip


def test_unmapped_assertions_need_a_marker_naming_a_step_with_an_expected_result() -> None:
    ok = "// expects: step 2\nawait qa.expectFieldFlagged('Message');\nawait qa.expectText('x'); // expects: overall\n"
    assert eg.unmapped(ok, {2}, True) == []
    assert eg.unmapped("await qa.expectText('x');\n", {2}, True) == [
        "Line 1: the assertion has no '// expects: step n' marker"
    ]
    assert eg.unmapped("await qa.expectText('x'); // expects: step 1\n", {2}, True) == [
        "Line 1: step 1 has no expected result to check"
    ]
    assert eg.unmapped("await page.goto('/');\n", {2}, True) == ["The script checks nothing: it has no assertion"]


