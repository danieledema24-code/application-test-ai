"""Rule-based Playwright emitter (P4-03a): an automation bundle from the P4-02 step models.

Bundle layout (paths are stable across versions):
- `pages/<Name>Page.ts`: one page object per discovered page a script uses, with one locator getter per field and
  control. Locators: `getByLabel` for labelled fields, `getByRole` with the accessible name for buttons and links,
  then `getByPlaceholder`, and CSS only when nothing else exists (with a `// fallback locator: <reason>` comment).
- `data/factories.ts`: the synthetic values of the test data items, per form; the saved test account is read from
  the environment at run time.
- `tests/<feature>/<TC-key>.spec.ts`: one spec per `suitable`/`partial` case, one `test.step` per case step, with
  `qa.expect*` assertions inside the step whose expected result they check. Specs that sign in turn traces off.

The output is deterministic: the same inputs always give the same code (no dates, sorted collections). Assertions
are recorded in `assertion_map` so later changes can be checked against them (expected-value guard, P4-03b/P4-08).
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from typing import Any

from app.domain.automation.steps import CaseIn, DataInfo, FieldInfo, FormInfo, SiteModel

RULES_HEADER = "Generated by rules (AI not configured)"
# Identifiers the spec guard refuses (domain/automation mirrors automation/src/spec-guard.ts) or JS reserves.
_UNSAFE_NAMES = frozenset(
    {"constructor", "prototype", "use", "extend", "connect", "launch", "tracing", "caller", "callee", "page", "goto",
     "form", "delete", "new", "class", "function", "default", "return", "this", "var", "let", "const", "if", "else",
     "for", "while", "do", "switch", "case", "break", "continue", "try", "catch", "finally", "throw", "typeof",
     "instanceof", "in", "of", "void", "with", "yield", "await", "async", "import", "export", "super", "null",
     "true", "false", "enum", "static", "get", "set", "qa", "test", "expect", "storageState", "setInputFiles"}
)  # fmt: skip


def q(text: str) -> str:
    """A TypeScript string literal."""
    return json.dumps(text, ensure_ascii=False).replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def one_line(text: str) -> str:
    return re.sub(r"[\r\n\u2028\u2029]+", " ", text).strip()


def sha256(code: str) -> str:
    return hashlib.sha256(code.encode()).hexdigest()


def _words(text: str) -> list[str]:
    return [w for w in re.split(r"[^A-Za-z0-9]+", text) if w]


def camel(text: str, fallback: str = "item") -> str:
    words = _words(text)
    if not words:
        return fallback
    out = words[0].lower() + "".join(w[:1].upper() + w[1:].lower() for w in words[1:])
    if out[0].isdigit():
        out = f"{fallback}{out[:1].upper()}{out[1:]}"
    if out in _UNSAFE_NAMES or re.search(r"(path|dir)$", out, re.I) or out.startswith("_"):
        out = f"{out}{fallback[:1].upper()}{fallback[1:]}"
    return out


def pascal(text: str, fallback: str = "Home") -> str:
    words = _words(text)
    out = "".join(w[:1].upper() + w[1:] for w in words) or fallback
    return out if out[0].isalpha() else f"Page{out}"


def page_class(path: str) -> str:
    segs = [s for s in path.strip("/").split("/") if s]
    base = pascal(" ".join(segs)) if segs else "Home"
    return f"{base}Page"


def feature_slug(text: str) -> str:
    slug = "-".join(w.lower() for w in _words(text))
    return slug or "general"


# ------------------------------------------------------------------ locators


@dataclass
class Locator:
    """One page-object getter: how the element is found (structured, so the live check can count it)."""

    getter: str
    element: str  # what a person calls it: "Message", "Send message", "Contact us form"
    by: str  # label | placeholder | role | form_role | form_button | css
    name: str = ""
    role: str = ""
    exact: bool = False
    within: str = ""  # "navigation" for primary navigation links
    css: str = ""
    fallback: str = ""  # why a weaker locator was used (written as a comment)
    used_by: set[str] = field(default_factory=set)

    def ts(self) -> str:
        p = "this.page"
        if self.by == "label":
            return f"{p}.getByLabel({q(self.name)})"
        if self.by == "placeholder":
            return f"{p}.getByPlaceholder({q(self.name)})"
        if self.by in ("role", "form_role"):
            role = "form" if self.by == "form_role" else self.role
            exact = ", exact: true" if self.exact else ""
            scope = f'{p}.getByRole("navigation").' if self.within == "navigation" else f"{p}."
            return f"{scope}getByRole({q(role)}, {{ name: {q(self.name)}{exact} }})"
        if self.by == "form_button":
            return f'{p}.locator("form").filter({{ has: {p}.getByRole("button", {{ name: {q(self.name)} }}) }})'
        return f"{p}.locator({q(self.css)})"

    def spec(self) -> dict[str, Any]:
        return {
            "getter": self.getter, "element": self.element, "by": self.by, "name": self.name, "role": self.role,
            "exact": self.exact, "within": self.within, "css": self.css, "fallback": self.fallback,
        }  # fmt: skip


@dataclass
class PageObject:
    path: str
    cls: str
    locators: dict[str, Locator] = field(default_factory=dict)  # key → locator (key: field key / control id)
    form_getters: dict[str, str] = field(default_factory=dict)  # form anchor → getter
    form_names: dict[str, str] = field(default_factory=dict)

    @property
    def file(self) -> str:
        return f"pages/{self.cls}.ts"

    def _unique(self, name: str) -> str:
        taken = {loc.getter for loc in self.locators.values()} | {"goto"}
        out, n = name, 2
        while out in taken:
            out, n = f"{name}{n}", n + 1
        return out

    def add(self, key: str, make: Any) -> Locator:
        if key not in self.locators:
            loc: Locator = make()
            loc.getter = self._unique(loc.getter)
            self.locators[key] = loc
        return self.locators[key]


def field_locator(fl: FieldInfo) -> Locator:
    getter = camel(fl.label or fl.name, "field")
    disc = fl.locator or ""
    if disc.startswith("getByPlaceholder("):
        name = _first_arg(disc) or fl.label
        return Locator(getter, fl.label, "placeholder", name=name)
    if disc.startswith("locator(") and not fl.label:
        return Locator(getter, fl.label or fl.name, "css", css=_first_arg(disc) or "input",
                       fallback="the field has no label or placeholder")  # fmt: skip
    return Locator(getter, fl.label, "label", name=fl.label)


def form_locator(form: FormInfo, getter: str) -> Locator:
    """A form is found by its submit button: most forms have no accessible name (no aria-label), so
    `getByRole("form")` would match nothing. Without a submit button, the accessible name is the only option."""
    if form.submit_label:
        return Locator(
            getter, f"{form.name} form", "form_button", name=form.submit_label,
            fallback=f"a form rarely has an accessible name, so it is found by its {q(form.submit_label)} button",
        )  # fmt: skip
    name = _named(form.locator) or form.name
    return Locator(getter, f"{form.name} form", "form_role", name=name)


def _first_arg(expr: str) -> str | None:
    m = re.match(r'^\w+\(("(?:[^"\\]|\\.)*")', expr)
    if not m:
        return None
    try:
        return str(json.loads(m.group(1)))
    except json.JSONDecodeError:
        return None


def _named(expr: str) -> str | None:
    m = re.search(r'name:\s*("(?:[^"\\]|\\.)*")', expr)
    if not m:
        return None
    try:
        return str(json.loads(m.group(1)))
    except json.JSONDecodeError:
        return None


# ------------------------------------------------------------------ bundle


@dataclass
class ScriptOut:
    lineage_id: str
    key: str
    path: str
    code: str
    sha256: str
    assertion_map: list[dict[str, Any]]
    locators: list[str]  # "<page file>#<getter>"
    signs_in: bool
    pages: list[str]


@dataclass
class Bundle:
    scripts: dict[str, ScriptOut] = field(default_factory=dict)  # case lineage → script
    assets: dict[str, str] = field(default_factory=dict)  # path → code (pages, data)
    locators: dict[str, list[dict[str, Any]]] = field(default_factory=dict)  # page file → locator specs
    pages: dict[str, str] = field(default_factory=dict)  # page file → URL path


@dataclass
class _Spec:
    case: CaseIn
    model: dict[str, Any]
    lines: list[str] = field(default_factory=list)
    poms: dict[str, PageObject] = field(default_factory=dict)  # path → page object
    factories: set[str] = field(default_factory=set)
    uses_credentials: bool = False
    uses_qa: bool = False
    assertion_map: list[dict[str, Any]] = field(default_factory=list)
    locators: list[str] = field(default_factory=list)


class Emitter:
    def __init__(self, site: SiteModel, *, credentials_ref: bool = True) -> None:
        self.site = site
        self.poms: dict[str, PageObject] = {}
        self.factories: dict[str, dict[str, DataInfo]] = {}  # export name → TD key → item
        self.factory_names: dict[str, str] = {}  # form anchor → export name
        self.credentials_used: set[str] = set()

    # ---------------------------------------------------------------- public

    def emit(self, cases: list[tuple[CaseIn, dict[str, Any]]]) -> Bundle:
        bundle = Bundle()
        specs: list[tuple[CaseIn, list[str], _Spec]] = []
        for case, model in sorted(cases, key=lambda cm: cm[0].key):
            spec = _Spec(case, model)
            body = self._body(spec)
            specs.append((case, body, spec))
        for case, body, spec in specs:
            path = f"tests/{self._feature(spec)}/{case.key}.spec.ts"
            code = self._spec_file(spec, body)
            bundle.scripts[case.lineage_id] = ScriptOut(
                case.lineage_id,
                case.key,
                path,
                code,
                sha256(code),
                spec.assertion_map,
                sorted(set(spec.locators)),
                bool(spec.model.get("signs_in")),
                sorted(spec.poms),
            )
        for path in sorted(self.poms):
            pom = self.poms[path]
            bundle.assets[pom.file] = self._pom_file(pom)
            bundle.pages[pom.file] = path
            bundle.locators[pom.file] = [
                {**loc.spec(), "used_by": sorted(loc.used_by)}
                for loc in sorted(pom.locators.values(), key=lambda x: x.getter)
            ]
        if self.factories or self.credentials_used:
            bundle.assets["data/factories.ts"] = self._factories_file()
        return bundle

    # ---------------------------------------------------------------- spec body

    def _pom(self, spec: _Spec, path: str) -> PageObject:
        if path not in self.poms:
            taken = {p.cls for p in self.poms.values()}
            cls, n = page_class(path), 2
            while cls in taken:
                cls, n = f"{page_class(path)[:-4]}{n}Page", n + 1
            self.poms[path] = PageObject(path, cls)
        pom = self.poms[path]
        spec.poms[path] = pom
        return pom

    @staticmethod
    def _var(pom: PageObject) -> str:
        return camel(pom.cls[:-4] if pom.cls.endswith("Page") else pom.cls, "screen")

    def _form_ref(self, spec: _Spec, anchor: str | None) -> str:
        anchor = anchor or ""
        form = self.site.form(anchor)
        if form is None:
            return q(anchor)
        pom = self._pom(spec, form.path)
        if anchor not in pom.form_getters:
            forms_here = list(self.site.forms_on(form.path))
            getter = "form" if len(forms_here) <= 1 else f"{camel(form.alias or form.name, 'some')}Form"
            pom.form_getters[anchor] = getter
            pom.form_names[anchor] = form.name
            pom.add(f"form:{anchor}", lambda: form_locator(form, getter))
        loc = pom.locators[f"form:{anchor}"]
        loc.used_by.add(spec.case.key)
        spec.locators.append(f"{pom.file}#{loc.getter}")
        return f"{self._var(pom)}.{pom.form_getters[anchor]}"

    def _field_ref(self, spec: _Spec, anchor: str, field_key: str) -> str:
        form = self.site.form(anchor)
        fl = form.field_by_key(field_key) if form else None
        if form is None or fl is None:
            raise ValueError(f"Unknown field {field_key}")
        pom = self._pom(spec, form.path)
        loc = pom.add(f"field:{field_key}", lambda: field_locator(fl))
        loc.used_by.add(spec.case.key)
        spec.locators.append(f"{pom.file}#{loc.getter}")
        return f"{self._var(pom)}.{loc.getter}"

    def _uses_field(self, spec: _Spec, anchor: str | None, field_key: Any) -> None:
        """A `qa.expect*` helper finds the field by its label: count that locator as used by the spec, so the live
        check covers it (a renamed label makes the script invalid). Only when the spec already uses the page object."""
        form = self.site.form(anchor)
        fl = form.field_by_key(str(field_key)) if form and field_key else None
        if form is None or fl is None or form.path not in spec.poms:
            return
        pom = spec.poms[form.path]
        loc = pom.add(f"field:{fl.key}", lambda: field_locator(fl))
        loc.used_by.add(spec.case.key)
        spec.locators.append(f"{pom.file}#{loc.getter}")

    def _control_ref(self, spec: _Spec, control: dict[str, Any], current: str | None) -> str:
        kind = control.get("type")
        name = str(control.get("name") or "")
        if kind == "submit":
            form = self.site.form(control.get("form"))
            path = form.path if form else (current or "/")
            pom = self._pom(spec, path)
            loc = pom.add(f"submit:{control.get('form')}",
                          lambda: Locator(camel(name, "submit"), name, "role", name=name, role="button"))  # fmt: skip
        elif kind in ("link", "nav_link"):
            path = str(control.get("page") or current or "/")
            pom = self._pom(spec, path)
            within = "navigation" if kind == "nav_link" else ""
            href = str(control.get("href") or "")
            if not name.strip() and href:
                # Discovery kept only the address of list items, so the link is found by it.
                loc = pom.add(f"href:{href}",
                              lambda: Locator(f"{camel(href.strip('/').replace('/', ' '), 'item')}Link", href, "css",
                                              css=f"a[href={q(href)}]",
                                              fallback="the link's text wasn't recorded, so it is found by its address"))  # fmt: skip
            else:
                loc = pom.add(f"{kind}:{name}",
                              lambda: Locator(f"{camel(name, 'item')}Link", name, "role", name=name, role="link",
                                              exact=True, within=within))  # fmt: skip
        else:
            path = str(control.get("page") or current or "/")
            pom = self._pom(spec, path)
            loc = pom.add(f"button:{name}",
                          lambda: Locator(f"{camel(name, 'item')}Button", name, "role", name=name, role="button"))  # fmt: skip
        loc.used_by.add(spec.case.key)
        spec.locators.append(f"{pom.file}#{loc.getter}")
        return f"{self._var(pom)}.{loc.getter}"

    def _value(self, spec: _Spec, anchor: str, value: dict[str, Any]) -> str:
        if "literal" in value:
            return q(str(value["literal"]))
        if value.get("secret"):
            spec.uses_credentials = True
            kind = str(value["secret"])
            name = "alteredPassword" if value.get("altered") else ("password" if kind == "password" else "username")
            self.credentials_used.add(name)
            spec.factories.add("credentials")
            return f"credentials.{name}"
        d = self.site.data.get(str(value.get("data")))
        if d is None:
            raise ValueError("Unknown test data item")
        form = self.site.form(d.form_anchor or anchor) or self.site.form(anchor)
        export = self._factory_name(form, d.form_anchor or anchor)
        self.factories.setdefault(export, {})[d.key] = d
        spec.factories.add(export)
        return f"{export}[{q(d.key)}]"

    def _factory_name(self, form: FormInfo | None, anchor: str) -> str:
        if anchor not in self.factory_names:
            base = f"{camel(form.alias or form.name, 'some') if form else 'some'}Form"
            taken = set(self.factory_names.values())
            name, n = base, 2
            while name in taken:
                name, n = f"{base}{n}", n + 1
            self.factory_names[anchor] = name
        return self.factory_names[anchor]

    def _assert(self, spec: _Spec, a: dict[str, Any], where: int | str) -> str:
        kind = a["kind"]
        spec.uses_qa = True
        form = a.get("form")
        args: list[str] = []
        if kind == "form_shown":
            helper, call = "expectFormShown", f"qa.expectFormShown({self._form_ref(spec, form)})"
        elif kind == "submission_blocked":
            helper, call = "expectSubmissionBlocked", f"qa.expectSubmissionBlocked({self._form_ref(spec, form)})"
        elif kind == "submission_accepted":
            text = a.get("text")
            extra = f", {q(text)}" if text else ""
            helper, call = (
                "expectSubmissionAccepted",
                f"qa.expectSubmissionAccepted({self._form_ref(spec, form)}{extra})",
            )
            args += [text] if text else []
        elif kind == "every_field_labelled":
            helper, call = "expectEveryFieldLabelled", f"qa.expectEveryFieldLabelled({self._form_ref(spec, form)})"
        elif kind == "field_flagged":
            helper, call = "expectFieldFlagged", f"qa.expectFieldFlagged({q(a['label'])})"
        elif kind == "field_length":
            opt = ", { atMost: true }" if a.get("at_most") else ""
            helper, call = "expectFieldLength", f"qa.expectFieldLength({q(a['label'])}, {int(a['n'])}{opt})"
            args += [str(a["n"]), "at most" if a.get("at_most") else "exactly"]
        elif kind in ("signed_in", "still_signed_in"):
            helper, call = "expectSignedIn", "qa.expectSignedIn()"
        elif kind == "not_signed_in":
            helper, call = "expectNotSignedIn", "qa.expectNotSignedIn()"
        elif kind == "error_shown":
            helper, call = "expectErrorShown", "qa.expectErrorShown()"
        elif kind == "text_visible":
            helper, call = "expectText", f"qa.expectText({q(a['text'])})"
        elif kind == "url_is":
            helper, call = "expectUrl", f"qa.expectUrl({q(a['path'])})"
        elif kind == "no_console_errors":
            helper, call = "expectNoConsoleErrors", "qa.expectNoConsoleErrors()"
        elif kind == "no_horizontal_overflow":
            helper, call = "expectNoHorizontalOverflow", "qa.expectNoHorizontalOverflow()"
        elif kind == "control_enabled":
            helper, call = "expectControlEnabled", f"qa.expectControlEnabled({q(a['name'])})"
        else:
            raise ValueError(f"Unknown assertion {kind}")
        if kind in ("field_flagged", "field_length"):
            self._uses_field(spec, form, a.get("field"))
        found = self.site.form(form) if form else None
        named = found.name if found is not None else None
        human = [x for x in (named, a.get("label"), a.get("path"), a.get("text") if kind == "text_visible" else None,
                             a.get("name")) if x]  # fmt: skip
        spec.assertion_map.append({"step": where, "helper": helper, "args": human + args, "kind": kind})
        return f"await {call};"

    def _body(self, spec: _Spec) -> list[str]:
        out: list[str] = []
        current: str | None = None
        for st in spec.model.get("steps", []):
            lines: list[str] = []
            pre = [a for a in st.get("assertions", []) if a.get("before_press")]
            post = [a for a in st.get("assertions", []) if not a.get("before_press")]
            for act in st.get("actions", []):
                kind = act["kind"]
                if kind == "open":
                    current = act["path"]
                    pom = self._pom(spec, current)
                    lines.append(f"await {self._var(pom)}.goto();")
                elif kind in ("fill", "paste"):
                    target = self._field_ref(spec, act["form"], act["field"])
                    lines.append(f"await {target}.fill({self._value(spec, act['form'], act['value'])});")
                elif kind == "leave_empty":
                    lines.append(f'await {self._field_ref(spec, act["form"], act["field"])}.fill("");')
                elif kind in ("press", "press_twice"):
                    lines += [self._assert(spec, a, st["n"]) for a in pre]
                    pre = []
                    ref = self._control_ref(spec, act["control"], current)
                    lines.append(f"await {ref}.{'dblclick' if kind == 'press_twice' else 'click'}();")
                    if act["control"].get("href"):
                        current = str(act["control"]["href"]).split("?")[0]
                elif kind == "back":
                    lines.append("await page.goBack();")
                elif kind == "reload":
                    lines.append("await page.reload();")
                elif kind == "set_viewport":
                    lines.append(
                        f"await page.setViewportSize({{ width: {int(act['width'])}, height: {int(act['height'])} }});"
                    )
                elif kind == "sign_in":
                    spec.uses_qa = True
                    login = self.site.login_form
                    target = login.path if login else (self.site.login_path or "/login")
                    lines.append(f"await qa.signIn({q(target)});")
                    current = None
                elif kind == "open_console":
                    lines.append("// The browser console is recorded for every test; nothing to open.")
                elif kind == "inspect":
                    lines.append("// Checked by the assertion below.")
            lines += [self._assert(spec, a, st["n"]) for a in pre + post]
            out.append(f"  await test.step({q(self._title(st))}, async () => {{")
            out += [f"    {ln}" for ln in lines] or ["    // No action."]
            out.append("  });")
        extra = spec.model.get("overall_extra") or []
        if extra:
            lines = [self._assert(spec, a, "overall") for a in extra]
            out.append(f"  await test.step({q('Check the expected result')}, async () => {{")
            out += [f"    {ln}" for ln in lines]
            out.append("  });")
        return out

    def _title(self, st: dict[str, Any]) -> str:
        """The step as people read it: test data written in (short values quoted), never a secret value."""
        text = one_line(str(st.get("text") or ""))
        for act in st.get("actions", []):
            value = act.get("value") or {}
            d = self.site.data.get(str(value.get("data"))) if value.get("data") else None
            if d is None:
                continue
            start = text.find(f"{d.key} (")
            if start < 0:
                continue
            depth, end = 0, -1
            for i in range(start + len(d.key) + 1, len(text)):
                if text[i] == "(":
                    depth += 1
                elif text[i] == ")":
                    depth -= 1
                    if depth == 0:
                        end = i
                        break
            if end < 0:
                continue
            inner = text[start + len(d.key) + 2 : end]
            if d.kind == "secret_ref" or d.value is None:
                shown = inner
            elif 0 < len(d.value) <= 40 and d.value.strip() and "\n" not in d.value:
                shown = f'"{d.value}"'
            elif d.kind == "valid":
                shown = f"a valid {d.field_label}"
                if text[end + 1 :].startswith(f" in {d.field_label}"):  # "Enter a valid Message", not "… in Message"
                    end += len(f" in {d.field_label}")
            else:
                shown = inner
            text = text[:start] + shown + text[end + 1 :]
        return text[:200]

    def _feature(self, spec: _Spec) -> str:
        for anchor in spec.model.get("forms", []):
            form = self.site.form(anchor)
            if form is not None:
                return feature_slug(form.alias or form.name)
        pages = spec.model.get("pages") or []
        if pages:
            segs = [s for s in str(pages[0]).strip("/").split("/") if s]
            return feature_slug(segs[0]) if segs else "home"
        return "general"

    # ---------------------------------------------------------------- files

    def _spec_file(self, spec: _Spec, body: list[str]) -> str:
        case = spec.case
        reqs = " · ".join(case.requirement_keys) if case.requirement_keys else "no linked requirement"
        lines = [
            f"// {case.key} v{case.version} · {reqs} · {RULES_HEADER}",
            f"// {one_line(case.title)}",
            'import { test } from "../../fixtures";',
        ]
        for path in sorted(spec.poms, key=lambda p: spec.poms[p].cls):
            lines.append(f'import {{ {spec.poms[path].cls} }} from "../../pages/{spec.poms[path].cls}";')
        if spec.factories:
            lines.append(f'import {{ {", ".join(sorted(spec.factories))} }} from "../../data/factories";')
        lines.append("")
        if spec.model.get("signs_in") or spec.uses_credentials:
            lines.append("// This test signs in: traces record typed values, so they are off for it.")
            lines.append('test.use({ trace: "off" });')
            lines.append("")
        tags = [f"@{case.key}"] + [f"@{s}" for s in sorted(case.suites) if re.fullmatch(r"[a-z][a-z0-9-]*", s)]
        params = ["page"] + (["qa"] if spec.uses_qa else [])
        lines.append(
            f"test({q(f'{case.key}: {one_line(case.title)}')}, {{ tag: [{', '.join(q(t) for t in tags)}] }}, "
            f"async ({{ {', '.join(params)} }}) => {{"
        )
        for path in sorted(spec.poms, key=lambda p: spec.poms[p].cls):
            pom = spec.poms[path]
            lines.append(f"  const {self._var(pom)} = new {pom.cls}(page);")
        lines += body
        lines.append("});")
        return "\n".join(lines) + "\n"

    def _pom_file(self, pom: PageObject) -> str:
        lines = [
            f"// Page object for {pom.path} · {RULES_HEADER}",
            "// Locators prefer labels and accessible roles; CSS is used only where nothing else identifies an element.",
            f'import type {{ {"Locator, " if pom.locators else ""}Page }} from "@playwright/test";',
            "",
            f"export class {pom.cls} {{",
            "  readonly page: Page;",
            "",
            "  constructor(page: Page) {",
            "    this.page = page;",
            "  }",
            "",
            "  async goto(): Promise<void> {",
            f"    await this.page.goto({q(pom.path)});",
            "  }",
        ]
        for loc in sorted(pom.locators.values(), key=lambda x: x.getter):
            lines.append("")
            if loc.by in ("form_role", "form_button"):
                lines.append(f"  /** The {one_line(loc.element)}. */")
                lines.append(f"  get {loc.getter}(): {{ name: string; locator: Locator }} {{")
                if loc.fallback:
                    lines.append(f"    // fallback locator: {one_line(loc.fallback)}")
                name = loc.element[:-5] if loc.element.endswith(" form") else loc.element
                lines.append(f"    return {{ name: {q(name)}, locator: {loc.ts()} }};")
            else:
                lines.append(f"  /** {one_line(loc.element)} */")
                lines.append(f"  get {loc.getter}(): Locator {{")
                if loc.fallback:
                    lines.append(f"    // fallback locator: {one_line(loc.fallback)}")
                lines.append(f"    return {loc.ts()};")
            lines.append("  }")
        lines.append("}")
        return "\n".join(lines) + "\n"

    def _factories_file(self) -> str:
        lines = [
            f"// Test data · {RULES_HEADER}",
            "// Synthetic values from the approved test data items (TD-…). They are not real people or real accounts.",
            "// The saved test account is read from the environment at run time; its values never appear here.",
        ]
        for export in sorted(self.factories):
            items = self.factories[export]
            first = next(iter(items.values()))
            form = self.site.form(first.form_anchor)
            lines.append("")
            lines.append(f"/** {one_line(form.name) if form else 'Form'} form */")
            lines.append(f"export const {export} = {{")
            for key in sorted(items):
                d = items[key]
                lines.append(f"  /** {one_line(d.field_label)} · {one_line(d.display or d.kind)} */")
                lines.append(f"  {q(key)}: {q(d.value or '')},")
            lines.append("} as const;")
        if self.credentials_used:
            lines.append("")
            lines.append(
                "/** The saved test account (Project settings), passed to the run only when a test signs in. */"
            )
            lines.append("export const credentials = {")
            if "username" in self.credentials_used:
                lines.append('  username: process.env.TEST_USERNAME ?? "",')
            if "password" in self.credentials_used:
                lines.append('  password: process.env.TEST_PASSWORD ?? "",')
            if "alteredPassword" in self.credentials_used:
                lines.append("  /** The saved password with characters added, so it is wrong. */")
                lines.append('  alteredPassword: `${process.env.TEST_PASSWORD ?? ""}-wrong`,')
            lines.append("};")
        return "\n".join(lines) + "\n"
