import type { TestCase } from "@prisma/client";
import { z } from "zod/v4";
import { prisma } from "../db.js";
import { parse } from "../lib/json.js";
import { aiJSON } from "./ai.js";

// Scripts are standard Playwright Test specs (see services/playwright-project.ts). They never
// contain credentials: logins read process.env.TEST_USERNAME / TEST_PASSWORD at run time.
export const SPEC_CONTRACT = `Standard Playwright Test spec (TypeScript):
  import { test, expect } from "../fixtures";   // re-exports @playwright/test with platform fixtures
  test("<KEY>: <title>", async ({ page }) => {
    await test.step("<manual step text>", async () => { ... });
  });
  - baseURL is configured: navigate with page.goto("/path")
  - credentials: process.env.TEST_USERNAME ?? "" and process.env.TEST_PASSWORD ?? ""`;

const Schema = z.object({ code: z.string().describe("Complete TypeScript spec file source") });

export async function generateScript(tc: TestCase, userName: string, discoveryHint?: unknown) {
  const steps = parse<{ action: string; expected?: string }[]>(tc.steps, []);
  const ai = await aiJSON({
    schema: Schema,
    task:
      "Convert this approved manual test case into a Playwright Test spec file.\n" +
      `Follow this contract exactly:\n${SPEC_CONTRACT}\n` +
      "Write exactly one test() named \"<KEY>: <title>\". Wrap each manual step in `await test.step(\"<step text>\", async () => { ... })`. " +
      "Prefer accessible locators (getByRole, getByLabel, getByText) and web-first assertions (await expect(locator).toBeVisible()). " +
      "Never hard-code credentials or perform real payments or destructive actions; if a step would, assert the control is present instead. " +
      "Start the file with a one-line comment naming the test case key.",
    input: { testCase: { key: tc.key, title: tc.title, preconditions: tc.preconditions, steps, expectedResult: tc.expectedResult }, pageStructure: discoveryHint ?? null },
  });
  const code = ai?.code ?? heuristicScript(tc, steps);
  const last = await prisma.script.findFirst({ where: { testCaseId: tc.id }, orderBy: { version: "desc" } });
  return prisma.script.create({
    data: {
      testCaseId: tc.id, testCaseVersion: tc.version, version: (last?.version ?? 0) + 1, language: "playwright-test", code,
      createdBy: ai ? `AI (Claude) for ${userName}` : `Rule-based generator for ${userName}`,
    },
  });
}

const q = (s: string) => JSON.stringify(s);

/** Best-effort translation of plain-English steps. Unrecognised steps become explicit TODOs that fail loudly. */
export function heuristicScript(tc: Pick<TestCase, "key" | "title" | "expectedResult">, steps: { action: string; data?: string; expected?: string }[]) {
  const lines = [
    `// ${tc.key}: ${tc.title}`,
    "// Generated by the rule-based generator (AI not configured). Review before relying on it.",
    'import { test, expect } from "../fixtures";',
    "",
    `test(${q(`${tc.key}: ${tc.title}`)}, async ({ page }) => {`,
  ];
  let navigated = false;
  for (const s of steps) {
    const body = translate(s.action, s.expected, s.data);
    if (body.some((l) => l.includes("page.goto"))) navigated = true;
    if (!navigated && !body.some((l) => l.includes("page.goto"))) {
      lines.push(`  await page.goto("/");`);
      navigated = true;
    }
    lines.push(`  await test.step(${q(s.action)}, async () => {`, ...body.map((l) => `    ${l}`), "  });");
  }
  if (!steps.length) lines.push('  await page.goto("/");');
  lines.push(`  await test.step("Verify expected result", async () => {`, "    await expect(page.locator(\"body\")).toBeVisible();");
  for (const t of quoted(tc.expectedResult)) lines.push(`    await expect(page.getByText(${q(t)}).first()).toBeVisible();`);
  lines.push("  });", "});");
  return lines.join("\n") + "\n";
}

function quoted(text = "") {
  return [...text.matchAll(/["“']([^"”']{2,60})["”']/g)].map((m) => m[1]);
}

function translate(action: string, expected?: string, data?: string): string[] {
  const a = action.trim();
  const out: string[] = [];
  const strs = quoted(a);
  const url = a.match(/(https?:\/\/\S+|\s(\/[\w\-./?=&]*))/);
  if (/\b(open|navigate|go to|visit|load)\b/i.test(a)) {
    const target = url?.[1]?.startsWith("http") ? q(url[1].replace(/[.,]$/, "")) : url?.[2] ? q(url[2].trim()) : '"/"';
    out.push(`const res = await page.goto(${target});`, "expect(res?.status() ?? 200).toBeLessThan(400);");
  } else if (/\b(enter|type|fill|input)\b/i.test(a)) {
    const field = a.match(/\b(?:in|into)\s+(?:the\s+)?["“']?([\w\s-]+?)["”']?\s*(?:field|input|box)?$/i)?.[1];
    const isPwd = /password/i.test(a);
    const value = /valid (user(name)?|email)/i.test(a) ? 'process.env.TEST_USERNAME ?? ""' : isPwd && /valid/i.test(a) ? 'process.env.TEST_PASSWORD ?? ""' : q(strs[0] ?? (data?.trim() || "test"));
    const label = field ?? (isPwd ? "Password" : /email/i.test(a) ? "Email" : null);
    out.push(label ? `await page.getByLabel(${q(label)}, { exact: false }).first().fill(${value});` : `throw new Error("TODO: automate step — field not identified: ${a.replace(/"/g, "'")}");`);
  } else if (/\b(click|press|tap|select|submit)\b/i.test(a)) {
    const name = strs[0] ?? a.match(/(?:click|press|tap|select)\s+(?:on\s+)?(?:the\s+)?([\w\s-]+?)(?:\s+(?:button|link|tab))?$/i)?.[1];
    if (/submit/i.test(a) && !name) out.push(`await page.locator("form [type=submit], form button").first().click();`);
    else if (name) out.push(`await page.getByRole("button", { name: ${q(name)} }).or(page.getByRole("link", { name: ${q(name)} })).first().click();`);
    else out.push(`throw new Error("TODO: automate step — control not identified: ${a.replace(/"/g, "'")}");`);
  } else if (/\b(verify|check|confirm|see|should|displayed|visible|appears)\b/i.test(a)) {
    if (/\btitle\b/i.test(a) && strs.length) out.push(`await expect(page).toHaveTitle(new RegExp(${q(strs[0].replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))}));`);
    else if (strs.length) for (const s of strs) out.push(`await expect(page.getByText(${q(s)}).first()).toBeVisible();`);
    else out.push(`await expect(page.locator("body")).toBeVisible();`);
  } else {
    out.push(`throw new Error("TODO: automate step manually: ${a.replace(/"/g, "'")}");`);
  }
  for (const s of quoted(expected)) out.push(`await expect(page.getByText(${q(s)}).first()).toBeVisible();`);
  return out;
}
