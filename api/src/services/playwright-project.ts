// Files for a standard Playwright Test project. The same files are used by the in-app runner
// (services/runner.ts) and by the downloadable project export, so a spec behaves identically
// on this platform, on a developer machine and on a remote Playwright browser grid.

export const PLAYWRIGHT_VERSION = "1.64.1";

/** Shared fixtures: network policy, console/network evidence and a masked final screenshot. */
export const FIXTURES_TS = `// Generated by Application Test AI. Specs import { test, expect } from here instead of
// "@playwright/test" so every test gets the same safety policy and evidence capture.
import { test as base, expect } from "@playwright/test";

const allowedHosts = (process.env.ATA_ALLOWED_HOSTS ?? "").split(",").map((h) => h.trim()).filter(Boolean);
const allowPrivate = process.env.ATA_ALLOW_PRIVATE === "true";
const METADATA = new Set(["169.254.169.254", "metadata.google.internal", "metadata", "100.100.100.200"]);
const PRIVATE = /^(10\\.|127\\.|0\\.|169\\.254\\.|192\\.168\\.|172\\.(1[6-9]|2\\d|3[01])\\.)/;

export const test = base.extend<{ _policy: void; _evidence: void }>({
  // Blocks cloud metadata endpoints always, and (when ATA_ALLOWED_HOSTS is set) top-level
  // navigation away from the approved application hosts.
  _policy: [async ({ context }, use) => {
    await context.route("**/*", (route) => {
      const req = route.request();
      let url: URL;
      try { url = new URL(req.url()); } catch { return route.abort(); }
      if (url.protocol === "data:" || url.protocol === "blob:") return route.continue();
      const host = url.hostname.replace(/^\\[|\\]$/g, "");
      const approved = !allowedHosts.length || allowedHosts.some((h) => host === h || host.endsWith("." + h));
      const offDomainNav = req.isNavigationRequest() && req.frame() === req.frame().page().mainFrame() && !approved;
      if (METADATA.has(host) || (!allowPrivate && !approved && PRIVATE.test(host)) || offDomainNav) {
        console.warn("BLOCKED by policy " + req.url());
        return route.abort("blockedbyclient");
      }
      return route.continue();
    });
    await use();
  }, { auto: true }],

  // Records browser console output and network errors, plus a final screenshot with password fields masked.
  _evidence: [async ({ page }, use, testInfo) => {
    const consoleLines: string[] = [];
    const networkLines: string[] = [];
    page.on("console", (m) => consoleLines.push("[" + new Date().toISOString() + "] " + m.type() + ": " + m.text()));
    page.on("pageerror", (e) => consoleLines.push("[" + new Date().toISOString() + "] pageerror: " + e.message));
    page.on("requestfailed", (r) => networkLines.push("FAILED " + r.method() + " " + r.url() + " — " + (r.failure()?.errorText ?? "unknown")));
    page.on("response", (r) => { if (r.status() >= 400) networkLines.push("HTTP " + r.status() + " " + r.request().method() + " " + r.url()); });
    await use();
    try {
      const shot = await page.screenshot({ fullPage: true, mask: [page.locator("input[type=password]")] });
      await testInfo.attach("final-state", { body: shot, contentType: "image/png" });
    } catch { /* page already closed */ }
    if (consoleLines.length) await testInfo.attach("console", { body: consoleLines.join("\\n"), contentType: "text/plain" });
    if (networkLines.length) await testInfo.attach("network", { body: networkLines.join("\\n"), contentType: "text/plain" });
  }, { auto: true }],
});

export { expect };
`;

