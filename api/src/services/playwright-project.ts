/** Specs may import from "@playwright/test"; the runner points them at the shared fixtures so the policy always applies. */
export function normaliseSpec(code: string) {
  return code.replace(/from\s+["']@playwright\/test["']/g, 'from "../fixtures"').replace(/from\s+["']\.\/fixtures["']/g, 'from "../fixtures"');
}

export const isPlaywrightTestSpec = (code: string) => /\btest\s*\(/.test(code) && /from\s+["'](\.\.?\/fixtures|@playwright\/test)["']/.test(code);
