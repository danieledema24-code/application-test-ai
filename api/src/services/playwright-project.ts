export const PLAYWRIGHT_VERSION = "1.64.1";

/** Shared fixtures: network policy, console/network evidence and a masked final screenshot. */
export const FIXTURES_TS = `// Generated by Application Test AI. Specs import { test, expect } from here instead of
// "@playwright/test" so every test gets the same safety policy and evidence capture.
import fs from "node:fs";
import path from "node:path";
import { test as base, expect } from "@playwright/test";

const allowedHosts = (process.env.ATA_ALLOWED_HOSTS ?? "").split(",").map((h) => h.trim()).filter(Boolean);
const allowPrivate = process.env.ATA_ALLOW_PRIVATE === "true";
const liveDir = process.env.ATA_LIVE_DIR;
const METADATA = new Set(["169.254.169.254", "metadata.google.internal", "metadata", "100.100.100.200"]);
const PRIVATE = /^(10\\.|127\\.|0\\.|169\\.254\\.|192\\.168\\.|172\\.(1[6-9]|2\\d|3[01])\\.)/;
// "::ffff:a9fe:a9fe" / "::ffff:169.254.169.254" are IPv4 addresses in IPv6 form; check them as IPv4.
const v4 = (host: string) => {
  const m = host.match(/^::ffff:([0-9a-f]{1,4}):([0-9a-f]{1,4})$/i);
  if (m) { const a = parseInt(m[1], 16), b = parseInt(m[2], 16); return [a >> 8, a & 255, b >> 8, b & 255].join("."); }
  return host.replace(/^::ffff:(?=\\d+\\.\\d+\\.\\d+\\.\\d+$)/i, "");
};

export const test = base.extend<{ _policy: void; _evidence: void; _live: void }>({
  // Blocks cloud metadata endpoints always, and (when ATA_ALLOWED_HOSTS is set) top-level
  // navigation away from the approved application hosts.
  _policy: [async ({ context, page }, use) => {
    // Only web pages can be opened: file://, chrome:// and similar would expose the machine running the tests.
    const frame = Object.getPrototypeOf(page.mainFrame());
    if (!frame.__ataGoto) {
      frame.__ataGoto = frame.goto;
      frame.goto = function (this: unknown, url: string, options?: unknown) {
        if (/^[a-z][\\w+.-]*:/i.test(url) && !/^(https?:|about:blank$|data:)/i.test(url)) throw new Error("BLOCKED by policy: only http(s) pages can be opened (" + url + ")");
        return frame.__ataGoto.call(this, url, options);
      };
    }
    await context.route("**/*", (route) => {
      const req = route.request();
      let url: URL;
      try { url = new URL(req.url()); } catch { return route.abort(); }
      if (url.protocol === "data:" || url.protocol === "blob:") return route.continue();
      const host = v4(url.hostname.replace(/^\\[|\\]$/g, "").toLowerCase());
      const approved = !allowedHosts.length || allowedHosts.some((h) => host === h || host.endsWith("." + h));
      const offDomainNav = req.isNavigationRequest() && req.frame() === req.frame().page().mainFrame() && !approved;
      if (METADATA.has(host) || host.startsWith("169.254.") || (!allowPrivate && !approved && PRIVATE.test(host)) || offDomainNav) {
        console.warn("BLOCKED by policy " + req.url());
        return route.abort("blockedbyclient");
      }
      return route.continue();
    });
    await use();
  }, { auto: true }],

  // Records browser console output and network errors, plus a final screenshot with password fields masked.
  _evidence: [async ({ page }, use, testInfo) => {
    const consoleLines: string[] = [];
    const networkLines: string[] = [];
    page.on("console", (m) => consoleLines.push("[" + new Date().toISOString() + "] " + m.type() + ": " + m.text()));
    page.on("pageerror", (e) => consoleLines.push("[" + new Date().toISOString() + "] pageerror: " + e.message));
    page.on("requestfailed", (r) => networkLines.push("FAILED " + r.method() + " " + r.url() + " — " + (r.failure()?.errorText ?? "unknown")));
    page.on("response", (r) => { if (r.status() >= 400) networkLines.push("HTTP " + r.status() + " " + r.request().method() + " " + r.url()); });
    await use();
    try {
      const shot = await page.screenshot({ fullPage: true, mask: [page.locator("input[type=password]")] });
      await testInfo.attach("final-state", { body: shot, contentType: "image/png" });
    } catch { /* page already closed */ }
    // Where the test ended up, so a failure can say what the page actually showed.
    try {
      const state = await page.evaluate(() => ({
        url: location.pathname + location.search,
        title: document.title,
        heading: document.querySelector("h1")?.textContent?.trim() ?? "",
        messages: Array.from(document.querySelectorAll('[role="alert"], .error, .alert, .ok, .success, .invalid-feedback'))
          .map((e) => (e.textContent ?? "").trim()).filter(Boolean).slice(0, 3),
      }));
      await testInfo.attach("page-state", { body: JSON.stringify(state), contentType: "application/json" });
    } catch { /* page already closed */ }
    if (consoleLines.length) await testInfo.attach("console", { body: consoleLines.join("\\n"), contentType: "text/plain" });
    if (networkLines.length) await testInfo.attach("network", { body: networkLines.join("\\n"), contentType: "text/plain" });
  }, { auto: true }],

  // When ATA_LIVE_DIR is set, streams the viewport as JPEG frames (one slot per worker) so the
  // platform can show the test while it runs. Chromium only; a no-op everywhere else.
  _live: [async ({ page }, use, testInfo) => {
    if (!liveDir) return use();
    const slot = path.join(liveDir, "w" + testInfo.parallelIndex);
    const state = (s: string) => { try { fs.writeFileSync(slot + ".json", JSON.stringify({ title: testInfo.title, state: s, at: Date.now() })); } catch { /* best effort */ } };
    state("running");
    let last = 0;
    const cdp = await page.context().newCDPSession(page).catch(() => null);
    if (cdp) {
      cdp.on("Page.screencastFrame", (f) => {
        cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }).catch(() => {});
        if (Date.now() - last < 100) return;
        last = Date.now();
        try {
          fs.writeFileSync(slot + ".tmp", Buffer.from(f.data, "base64"));
          fs.renameSync(slot + ".tmp", slot + ".jpg");
        } catch { /* best effort */ }
      });
      await cdp.send("Page.startScreencast", { format: "jpeg", quality: 60, maxWidth: 1280, maxHeight: 860 }).catch(() => {});
    }
    await use();
    state(testInfo.status === testInfo.expectedStatus ? "passed" : "failed");
    await cdp?.send("Page.stopScreencast").catch(() => {});
  }, { auto: true }],
});

export { expect };
`;

