export function packageJson(projectName: string) {
  const slug = projectName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "app";
  return JSON.stringify({
    name: `${slug}-playwright-tests`, private: true, version: "1.0.0",
    scripts: { test: "playwright test", "test:headed": "playwright test --headed", report: "playwright show-report" },
    devDependencies: { "@playwright/test": `^${PLAYWRIGHT_VERSION}`, "@types/node": "^22.0.0" },
  }, null, 2) + "\n";
}

export function envExample(baseUrl: string) {
  return [
    "# Copy to .env (or export these variables) before running the tests.",
    `BASE_URL=${baseUrl}`,
    "TEST_USERNAME=",
    "TEST_PASSWORD=",
    "# Optional: run on a remote Playwright browser server / grid instead of local browsers",
    "# PW_WS_ENDPOINT=wss://your-grid.example.com/playwright",
    "# Optional: restrict navigation to these hosts (comma separated)",
    `# ATA_ALLOWED_HOSTS=${safeHost(baseUrl)}`,
    "",
  ].join("\n");
}

function safeHost(u: string) {
  try {
    return new URL(u).hostname;
  } catch {
    return "";
  }
}

