import { z } from "zod/v4";
import { aiJSON } from "./ai.js";
import type { DiscoveredPage } from "./discovery.js";

export const CATEGORIES = ["FUNCTIONAL", "POSITIVE", "NEGATIVE", "BOUNDARY", "REGRESSION", "UI", "FORM_VALIDATION", "AUTHENTICATION", "ACCESSIBILITY", "API"] as const;
export const PRIORITIES = ["CRITICAL", "HIGH", "MEDIUM", "LOW"] as const;

const CaseSchema = z.object({
  title: z.string().describe("Short, specific outcome being verified, e.g. \"Contact form rejects an invalid email address\""),
  description: z.string().describe("Objective: one or two plain sentences on what is verified and why it matters"),
  preconditions: z.string().describe("One condition per line, starting with \"• \", e.g. the start page, user state and data that must exist"),
  steps: z.array(z.object({
    action: z.string().describe("One concrete action in the imperative, with exact paths and quoted UI labels"),
    data: z.string().describe("Exact test data typed or selected in this step, or empty string when none"),
    expected: z.string().describe("What the tester should observe immediately after this action"),
  })),
  expectedResult: z.string().describe("The overall pass criterion for the whole case"),
  category: z.enum(CATEGORIES),
  priority: z.enum(PRIORITIES),
});
export type GeneratedCase = z.infer<typeof CaseSchema>;
const ResultSchema = z.object({ cases: z.array(CaseSchema), notes: z.string().describe("Assumptions made and gaps you could not cover") });

export type GenerationSource = "DISCOVERY" | "USER_STORY" | "REQUIREMENTS" | "DESCRIPTION" | "OPENAPI";

export async function generateCases(opts: {
  source: GenerationSource; text?: string; pages?: DiscoveredPage[]; workflows?: unknown; categories?: string[]; count?: number; applicationUrl: string;
}): Promise<{ cases: GeneratedCase[]; generatedBy: "claude" | "heuristic"; notes: string }> {
  const count = Math.min(Math.max(opts.count ?? 12, 1), 40);
  const categories = opts.categories?.length ? opts.categories : ["FUNCTIONAL", "POSITIVE", "NEGATIVE", "FORM_VALIDATION", "BOUNDARY", "UI", "AUTHENTICATION", "ACCESSIBILITY"];
  const input =
    opts.source === "DISCOVERY"
      ? { applicationUrl: opts.applicationUrl, pages: (opts.pages ?? []).map((p) => ({ url: p.url, title: p.title, headings: p.headings, nav: p.navItems, buttons: p.buttons.slice(0, 20), forms: p.forms })), workflows: opts.workflows }
      : { applicationUrl: opts.applicationUrl, [opts.source.toLowerCase()]: opts.text };
  const ai = await aiJSON({
    schema: ResultSchema,
    task:
      `Write up to ${count} manual test cases for the application, from the ${opts.source.toLowerCase().replace("_", " ")} below. ` +
      `Use only these categories: ${categories.join(", ")}. Mix positive, negative and boundary scenarios where relevant. ` +
      "Write every case so a new tester can follow it without knowing the application: " +
      "a clear objective; preconditions one per line; 4 to 10 numbered steps with exactly one action each; " +
      "the exact test data for each step in its data field (realistic sample values such as jane.doe@example.com); " +
      "and a specific, observable expected result for every step (what appears, changes or is blocked), never vague wording like \"works\" or \"is correct\". " +
      "Start with opening the exact URL path and end with a verification step. " +
      "Use exact URL paths and quoted UI text where known, e.g. Click \"Sign in\". Never include real credentials; refer to \"a valid test user\". " +
      "Do not invent features that the input does not support; record assumptions in notes.",
    input,
  });
  if (ai) return { cases: ai.cases.slice(0, count), generatedBy: "claude", notes: ai.notes };
  // Discovery guidance text is applied too, so "Message is required" adds that case on top of the page-based ones.
  const fromGuidance = opts.text?.trim() ? fromText(opts.text, opts.pages ?? []) : [];
  const all = opts.source === "DISCOVERY" ? [...fromGuidance, ...fromPages(opts.pages ?? [])] : fromGuidance;
  const cases = all.filter((x, i) => all.findIndex((y) => y.title === x.title) === i);
  const filtered = cases.filter((c) => categories.includes(c.category));
  return {
    cases: (filtered.length ? filtered : cases).slice(0, count),
    generatedBy: "heuristic",
    notes: opts.source === "DISCOVERY"
      ? "Generated by the rule-based generator because AI is not configured. Cases come from the discovered pages and forms and need human review."
      : `Generated by the rule-based generator because AI is not configured. Required fields, email validation, length limits, success messages and sign-in in the text became concrete cases${opts.pages?.length ? " using the fields found by the latest discovery" : "; run a discovery so the real field labels are used"}. Sentences it could not interpret are marked "Manual check".`,
  };
}

type Step = [action: string, expected: string, data?: string];
const c = (category: GeneratedCase["category"], priority: GeneratedCase["priority"], title: string, steps: Step[], expectedResult: string, preconditions: string[] = [], description = ""): GeneratedCase => ({
  title, description: description || title, preconditions: preconditions.map((p) => `• ${p}`).join("\n"),
  steps: steps.map(([action, expected, data]) => ({ action, expected, data: data ?? "" })), expectedResult, category, priority,
});

function pathOf(url: string) {
  try {
    const u = new URL(url);
    return u.pathname + u.search;
  } catch {
    return url;
  }
}

type Field = DiscoveredPage["forms"][number]["fields"][number];
const label = (f: Field) => f.label || f.name || f.type;

/** Realistic sample value for a field, so the tester (and the generated script) uses concrete data. */
function sample(f: Field): string {
  const k = `${f.label} ${f.name}`.toLowerCase();
  if (f.type === "textarea" || /message|comment|feedback|description/.test(k)) return "Hello, I would like to know when my order will arrive.";
  if (f.type === "email" || /e-?mail/.test(k)) return "jane.doe@example.com";
  if (f.type === "tel" || /phone|mobile/.test(k)) return "+44 7700 900123";
  if (f.type === "number" || /\b(qty|quantity|amount|age)\b/.test(k)) return "2";
  if (f.type === "url" || /website|url/.test(k)) return "https://example.com";
  if (f.type === "date") return "2026-12-01";
  if (/first/.test(k)) return "Jane";
  if (/last|surname/.test(k)) return "Doe";
  if (/name/.test(k)) return "Jane Doe";
  if (/search|query/.test(k)) return "shoes";
  if (/post|zip/.test(k)) return "SW1A 1AA";
  if (/city|town/.test(k)) return "London";
  return "Sample text";
}

/** Readable page names: the browser title when only one page uses it, otherwise the path (many sites reuse one title everywhere). */
function pageNamer(pages: DiscoveredPage[]) {
  const uses = new Map<string, number>();
  for (const p of pages) uses.set(p.title, (uses.get(p.title) ?? 0) + 1);
  return (p: DiscoveredPage) => {
    const path = pathOf(p.url);
    if (p.title && uses.get(p.title) === 1) return p.title;
    const slug = titleFromPath(path).replace(/^sign ?in$/i, "Sign-in").replace(/^sign ?up$/i, "Sign-up").replace(/^log ?in$/i, "Login");
    return path === "/" ? "the home page" : `the ${slug} page (${path})`;
  };
}

/** A password form that creates an account rather than signing in. */
const isSignUp = (path: string, fields: Field[]) =>
  /sign-?up|register|join|create-account/i.test(path) || fields.filter((x) => x.type === "password").length > 1
  || fields.some((x) => x.type !== "password" && /\bname\b/i.test(label(x)));

function fromPages(pages: DiscoveredPage[]): GeneratedCase[] {
  const out: GeneratedCase[] = [];
  const nameOf = pageNamer(pages);
  for (const p of pages.slice(0, 8)) {
    const path = pathOf(p.url);
    const name = nameOf(p);
    const heading = p.headings[0];
    const reachable = `The application is reachable and ${path} is publicly accessible`;
    const open: Step = [`Open ${path}`, heading ? `The page loads and the heading "${heading}" is displayed` : "The page loads without an error page or blank screen"];

    out.push(c("FUNCTIONAL", "HIGH", `${name.replace(/^the /, "The ")} loads successfully`, [
      [`Open ${path}`, "The page responds without an error page, blank screen or browser warning"],
      [`Verify the page title contains "${p.title}"`, `The browser tab shows the title ${p.title}`],
      ...(heading ? [[`Verify the heading "${heading}" is displayed`, "The main heading is visible near the top of the page"] as Step] : []),
    ], `The ${name} page opens with the correct title and its main content visible, and no errors are shown`,
    [reachable], `Confirms that ${path} can be opened directly and renders its main content.`));

    if (heading) out.push(c("UI", "MEDIUM", `Main heading is visible on ${name}`, [
      [`Open ${path}`, "The page loads completely"],
      [`Verify "${heading}" is displayed`, "The heading text is fully visible, readable and not cut off"],
    ], `The heading "${heading}" is shown at the top of ${name}`, [reachable], `Checks that the primary heading on ${name} is rendered for the user.`));

    for (const f of p.forms.slice(0, 2)) {
      const required = f.fields.filter((x) => x.required);
      const signup = f.fields.some((x) => x.type === "password") && isSignUp(path, f.fields);
      const pwd = f.fields.some((x) => x.type === "password") && !signup;
      const kind = pwd ? "login" : "form";
      if (signup) {
        out.push(c("POSITIVE", "HIGH", `Create an account on ${name} with valid data`, [
          open,
          ...f.fields.map((x): Step => x.type === "password"
            ? [`Enter "Str0ng-Passw0rd!" in the "${label(x)}" field`, "The password is accepted and shown masked as dots", "Str0ng-Passw0rd!"]
            : [`Enter "${sample(x)}" in the "${label(x)}" field`, "The value appears in the field with no error message", sample(x)]),
          ["Submit the form", "The account is created without validation errors"],
          ["Verify no error message is shown", "The user is signed in or told to confirm their email; no error is displayed"],
        ], "A new account is created and the user is signed in or asked to confirm their email",
        [reachable, "Creates a real account: run only on a test environment, and use an email address that has not signed up before"],
        `Verifies that a new visitor can create an account on ${name}.`));
      }
      const fill = f.fields.map((x): Step => x.type === "password"
        ? [`Enter a valid password in the "${label(x)}" field`, "The password is accepted and shown masked as dots", "Password of the test user (from the environment credentials)"]
        : pwd ? [`Enter a valid username in the "${label(x)}" field`, "The value appears in the field with no error message", "Username of the test user (from the environment credentials)"]
        : [`Enter "${sample(x)}" in the "${label(x)}" field`, "The value appears in the field with no error message", sample(x)]);

      if (!signup) out.push(c(pwd ? "AUTHENTICATION" : "POSITIVE", "HIGH", `Submit ${kind} on ${name} with valid data`,
        [open, ...fill, ["Submit the form", pwd ? "The sign-in request is sent and a loading state or redirect follows" : "The form is submitted without validation errors"],
          pwd ? ["Verify the user is signed in", "The sign-in form is no longer shown and no error message appears"] : ["Verify a confirmation message is shown", "A success or thank-you message appears and no error message is shown"]],
        pwd ? "The user is signed in, redirected to an authenticated page and sees their account area" : "The submission succeeds and a confirmation message is shown; no error is displayed",
        pwd ? [reachable, "A valid test user exists and its credentials are stored on the environment", "The user is signed out"] : [reachable],
        pwd ? `Verifies that a registered user can sign in on ${name}.` : `Verifies the happy path of the form on ${name} with realistic valid data.`));

      out.push(c("FORM_VALIDATION", "HIGH", `Required field validation on ${name}`, [
        open,
        ["Submit the form without entering any values", "The form is not submitted and the page stays on the form"],
        ["Verify the form is not accepted", `The form stays on screen and each empty required field${required.length ? ` (${required.map(label).join(", ")})` : ""} shows a message explaining it is required`],
      ], `Validation messages are shown for required fields${required.length ? ` (${required.map(label).join(", ")})` : ""} and nothing is submitted`,
      [reachable, "All form fields are empty"], `Checks that the form on ${name} cannot be submitted while required fields are empty.`));

      // Fields the page does not mark as required but that a form like this normally needs. These are assumptions:
      // the case says so, and a tester deletes it if the field really is optional.
      if (!pwd) {
        const unmarked = f.fields.filter((x) => !x.required && ["text", "textarea", "email"].includes(x.type) && !/optional/i.test(label(x))).slice(0, 2);
        for (const field of unmarked) out.push({ ...requiredCase(name, open, f.fields, field,
          [reachable, `Assumption: ${label(field)} is mandatory (the page does not mark it as required). Confirm with the requirements and delete this case if the field is optional.`],
          `Checks that the form on ${name} cannot be sent without ${label(field)}. Generated as an assumption because the field is not marked required.`), priority: "MEDIUM" });
      }

      if (pwd) {
        const user = f.fields.find((x) => x.type !== "password");
        out.push(c("NEGATIVE", "HIGH", `Login rejects invalid password on ${name}`, [
          open,
          [`Enter a valid username in the "${user ? label(user) : "username"}" field`, "The value appears in the field", "Username of the test user"],
          ['Enter "wrong-password-123" in the "Password" field', "The password is shown masked as dots", "wrong-password-123"],
          ["Submit the form", "The sign-in attempt is refused"],
          ["Verify an error message about invalid credentials is displayed", "An error message is shown and the user remains on the sign-in page"],
        ], "An error message is displayed, the user is not signed in and no account details are revealed",
        [reachable, "A valid test user exists", "The user is signed out"], `Ensures sign-in on ${name} fails safely with a wrong password.`));
      }
      const email = f.fields.find((x) => x.type === "email");
      if (email) out.push(c("NEGATIVE", "MEDIUM", `Invalid email format rejected on ${name}`, [
        open,
        [`Enter "not-an-email" in the "${label(email)}" field`, "The value appears in the field", "not-an-email"],
        ["Submit the form", "The form is not submitted"],
        ["Verify the form is not accepted", "A message asks for a valid email address next to the field and no success message appears"],
      ], "An email format validation message is shown and the form is not submitted", [reachable], `Checks email format validation on ${name}.`));

      const text = f.fields.find((x) => ["text", "textarea"].includes(x.type));
      if (text) out.push(c("BOUNDARY", "LOW", `Maximum length input in "${label(text)}" on ${name}`, [
        open,
        // Other fields get valid values so the long input is what the application actually receives.
        ...f.fields.filter((x) => x !== text).map((x): Step => [`Enter "${sample(x)}" in the "${label(x)}" field`, "The value appears in the field with no error message", sample(x)]),
        [`Enter "${"A".repeat(256)}" in the "${label(text)}" field`, "The input is either limited to the maximum length or accepted without breaking the layout", "256 × the letter A"],
        ["Submit the form", "The application responds with a validation message or success"],
        ["Verify no server error is shown", "No server error, exception or blank page is displayed"],
      ], "Long input is handled gracefully and no server error or broken layout appears", [reachable],
      `Checks the upper length boundary of the ${label(text)} field on ${name}.`));
    }
  }
  if (pages.length) {
    const nav = [...new Set(pages.flatMap((p) => p.navItems))].slice(0, 6);
    if (nav.length) out.push(c("REGRESSION", "MEDIUM", "Primary navigation links work", [
      ["Open the home page /", "The home page loads with the main navigation visible"],
      ...nav.map((n): Step => [`Click "${n}"`, `The ${n} page opens without an error`]),
    ], "Every primary navigation item opens a working page", ["The application is reachable"], "Checks each item in the main navigation leads to a working page."));
    out.push(c("ACCESSIBILITY", "MEDIUM", "Keyboard navigation and focus visibility", [
      ["Open the home page /", "The home page loads"],
      ["Press Tab repeatedly through the interactive elements", "Focus moves through links, buttons and fields in a logical reading order"],
      ["Verify the focus indicator is visible on each element", "The focused element always has a clearly visible outline or highlight"],
    ], "All interactive elements are reachable by keyboard with a visible focus indicator", ["The application is reachable", "Use a keyboard only (no mouse)"],
    "Checks that keyboard-only users can reach and see every interactive element."));
    out.push(c("ACCESSIBILITY", "LOW", "Images and form fields have accessible names", [
      ["Open the home page /", "The home page loads"],
      ["Check images for alt text and inputs for labels", "Every meaningful image has alt text and every input has a visible or programmatic label"],
    ], "Images have alt text and every input has a label", ["The application is reachable", "Browser developer tools or a screen reader is available"],
    "Checks basic accessible naming for screen-reader users."));
  }
  return out;
}

/** "Enter <sample> in the <label> field" (or the test user's credentials for login fields). */
function fillStep(x: Field, login = false): Step {
  if (x.type === "password") return [`Enter a valid password in the "${label(x)}" field`, "The password is accepted and shown masked as dots", "Password of the test user (from the environment credentials)"];
  if (login) return [`Enter a valid username in the "${label(x)}" field`, "The value appears in the field with no error message", "Username of the test user (from the environment credentials)"];
  return [`Enter "${sample(x)}" in the "${label(x)}" field`, "The value appears in the field with no error message", sample(x)];
}

/** Fill every other field, leave one empty, submit, and expect the form to be refused. */
function requiredCase(pageName: string, open: Step, fields: Field[], field: Field, pre: string[], why: string) {
  return c("FORM_VALIDATION", "HIGH", `"${label(field)}" is required on ${pageName}`, [
    open,
    ...fields.filter((x) => x !== field).map((x) => fillStep(x)),
    [`Leave the "${label(field)}" field empty`, "The field stays empty"],
    ["Submit the form", "The submission is blocked or answered with a validation message"],
    ["Verify the form is not accepted", `A message asks for ${label(field)} and no success message appears`],
  ], `The form is not accepted while ${label(field)} is empty`, pre, why);
}

const titleFromPath = (p: string) => p.split("/").filter(Boolean).pop()?.replace(/[-_]+/g, " ").replace(/^\w/, (m) => m.toUpperCase()) || "Home";

/** The discovered page the text is about: an explicit path wins, then a page named in the text, then a form whose fields are mentioned. */
function findPage(text: string, pages: DiscoveredPage[], login: boolean): DiscoveredPage | undefined {
  const t = text.toLowerCase();
  const path = text.match(/(?:^|\s)(\/[\w\-./]*)/)?.[1]?.replace(/[.,]$/, "");
  const score = (p: DiscoveredPage) => {
    const name = (p.title.split(/[·|–-]/)[0] ?? "").trim().toLowerCase();
    const labels = p.forms.flatMap((f) => f.fields.map((x) => label(x).toLowerCase()));
    return (path && pathOf(p.url) === path ? 10 : 0) + (name && t.includes(name) ? 3 : 0)
      + labels.filter((l) => l.length > 2 && t.includes(l)).length + (login && p.forms.some((f) => f.fields.some((x) => x.type === "password")) ? 2 : 0);
  };
  const best = [...pages].sort((a, b) => score(b) - score(a))[0];
  return best && score(best) > 0 ? best : undefined;
}

/** Field names from "X, Y and Z are required" and "the X field", for when no discovered form is available. */
function fieldsFromText(sentences: string[], login: boolean): Field[] {
  const names = sentences.flatMap((s) => [
    ...(s.match(/^(.*?)\b(?:is|are)\s+(?:required|mandatory)\b/i)?.[1].replace(/^(the|all|both)\s+/i, "").split(/,|\band\b|&/) ?? []),
    ...[...s.matchAll(/(?:^|\s)[Tt]he\s+["“]?([A-Z][\w ]{0,24}?)["”]?\s+field\b/g)].map((m) => m[1]),
  ]).map((n) => n.replace(/\b(the|fields?)\b/gi, "").trim()).filter((n) => n && n.split(/\s+/).length <= 3);
  if (sentences.some((s) => /e-?mail/i.test(s)) && !names.some((n) => /e-?mail/i.test(n))) names.push("Email");
  if (login && !names.some((n) => /password/i.test(n))) names.push("Password");
  return [...new Set(names)].map((n) => ({ name: n.toLowerCase(), label: n, required: false, type: /e-?mail/i.test(n) ? "email" : /message|comment|description/i.test(n) ? "textarea" : /password/i.test(n) ? "password" : "text" }));
}

/**
 * Rule-based cases from a feature description, user story or requirements. Sentences about required fields,
 * email validity, success messages, sign-in and length limits become concrete, automatable cases. The page and
 * its fields come from the latest discovery when it found the page, otherwise from the text. Anything else
 * becomes a case marked for manual completion.
 */
function fromText(text: string, pages: DiscoveredPage[] = []): GeneratedCase[] {
  const sentences = text.split(/\n+|(?<=[.!?])\s+/).map((s) => s.replace(/^[-*•\d.)\s]+/, "").trim()).filter((s) => s.length > 3);
  const login = /\b(sign|log)[\s-]?in\b|\blogin\b|password/i.test(text);
  const page = findPage(text, pages, login);
  const explicitPath = text.match(/(?:^|\s)(\/[\w\-./]*)/)?.[1]?.replace(/[.,]$/, "");
  const path = explicitPath ?? (page ? pathOf(page.url) : login ? "/login" : "/");
  const form = page?.forms.find((f) => login === f.fields.some((x) => x.type === "password")) ?? page?.forms[0];
  // A page without the form (e.g. /login discovered while signed in) only lends its path, not its title.
  const pageName = form ? page!.title : login ? "the sign-in page" : page?.title || titleFromPath(path);
  const fields = form?.fields.length ? form.fields : fieldsFromText(sentences, login);
  const isLoginForm = fields.some((x) => x.type === "password");
  const open: Step = [`Open ${path}`, "The page loads without an error"];
  const pre = [`The application is reachable and ${path} can be opened`,
    ...(form ? [] : ["Field labels are taken from the text; adjust them if the page uses different wording (run a discovery to use the real ones)"]),
    ...(!explicitPath && !page ? [`The page path ${path} is assumed; change the first step if the page lives elsewhere`] : [])];
  const find = (n: string) => fields.find((f) => label(f).toLowerCase() === n.toLowerCase()) ?? fields.find((f) => label(f).toLowerCase().includes(n.toLowerCase()));
  const out: GeneratedCase[] = [];
  const unmatched: string[] = [];
  let happy = false;
  // The sentence that describes success (if any) supplies the happy path's confirmation; context sentences
  // ("lets a visitor send…", "I want to…") are covered by that same happy path.
  const SUCCESS = /thank|success|confirm|\b(is|are) (shown|displayed)\b|\bappears?\b|redirect/i;
  const CONTEXT = /\b(lets|allows|enables|can)\b|\bi want\b|\bso that\b/i;
  const successSentence = sentences.find((s) => SUCCESS.test(s) && !/\b(error|wrong|invalid)\b/i.test(s));

  for (const s of sentences) {
    if (isLoginForm && /\b(wrong|invalid|incorrect)\b.*\bpassword\b|\bpassword\b.*\b(wrong|invalid|incorrect)\b/i.test(s)) continue; // covered by the wrong-password case below
    if (happy && fields.length && (s === successSentence || CONTEXT.test(s))) continue;
    const req = s.match(/^(.*?)\b(?:is|are)\s+(?:required|mandatory)\b/i);
    const max = s.match(/\b(?:max(?:imum)?|at most|up to|no more than|limited to)\s+(\d+)\s*(?:characters|chars)\b/i);
    if (req && fields.length) {
      const named = req[1].replace(/^(the|all|both)\s+/i, "").split(/,|\band\b|&/).map((n) => n.replace(/\b(the|fields?)\b/gi, "").trim()).filter(Boolean);
      for (const f of named.map(find).filter((x): x is Field => Boolean(x)))
        out.push(requiredCase(pageName, open, fields, f, pre, `From the requirement "${s}": the form must not be sent without ${label(f)}.`));
    } else if (/e-?mail/i.test(s) && /\bvalid\b/i.test(s) && fields.some((x) => x.type === "email" || /e-?mail/i.test(label(x)))) {
      const email = fields.find((x) => x.type === "email" || /e-?mail/i.test(label(x)))!;
      out.push(c("NEGATIVE", "MEDIUM", `Invalid email address is rejected on ${pageName}`, [
        open,
        ...fields.filter((x) => x !== email).map((x) => fillStep(x, isLoginForm)),
        [`Enter "not-an-email" in the "${label(email)}" field`, "The value appears in the field", "not-an-email"],
        ["Submit the form", "The submission is blocked or answered with a validation message"],
        ["Verify the form is not accepted", "A message asks for a valid email address and no success message appears"],
      ], "The form is not accepted with an invalid email address", pre, `From the requirement "${s}".`));
    } else if (max && fields.some((x) => ["text", "textarea"].includes(x.type))) {
      const n = Number(max[1]);
      const target = fields.find((x) => s.toLowerCase().includes(label(x).toLowerCase())) ?? fields.find((x) => ["text", "textarea"].includes(x.type))!;
      out.push(c("BOUNDARY", "MEDIUM", `"${label(target)}" longer than ${n} characters on ${pageName}`, [
        open,
        ...fields.filter((x) => x !== target).map((x) => fillStep(x)),
        [`Enter "${"A".repeat(n + 1)}" in the "${label(target)}" field`, `The field stops at ${n} characters or the value is refused`, `${n + 1} × the letter A`],
        ["Submit the form", "The application limits or refuses the value"],
        ["Verify no server error is shown", "No server error, exception or blank page is displayed"],
      ], `Input over ${n} characters is limited or refused without a server error`, pre, `From the requirement "${s}".`));
    } else if ((s === successSentence || CONTEXT.test(s)) && fields.length && !happy) {
      happy = true;
      const shown = [...(successSentence ?? s).matchAll(/["“]([^"”]{2,80})["”]/g)].map((m) => m[1]);
      out.push(c(isLoginForm ? "AUTHENTICATION" : "POSITIVE", "HIGH", isLoginForm ? `Sign in on ${pageName} with valid credentials` : `Submit ${pageName} with valid data`, [
        open,
        ...fields.map((x) => fillStep(x, isLoginForm)),
        ["Submit the form", "The form is sent"],
        isLoginForm ? ["Verify the user is signed in", "The sign-in form is no longer shown and no error message appears"]
          : ["Verify a confirmation message is shown", shown.length ? `The message "${shown[0]}" appears` : "A success or thank-you message appears and no error message is shown"],
      ], isLoginForm ? "The user is signed in and sees their account area" : `The form is sent and a confirmation is shown${shown.length ? `: "${shown[0]}"` : ""}`,
      isLoginForm ? [...pre, "A valid test user exists and its credentials are stored on the environment"] : pre, `From "${[s, successSentence].filter((x, i, a) => x && a.indexOf(x) === i).join(" ")}".`));
    } else unmatched.push(s);
  }

  if (isLoginForm) {
    const user = fields.find((x) => x.type !== "password");
    out.push(c("NEGATIVE", "HIGH", `Sign-in with a wrong password is refused on ${pageName}`, [
      open,
      [`Enter a valid username in the "${user ? label(user) : "Email"}" field`, "The value appears in the field", "Username of the test user"],
      ['Enter "wrong-password-123" in the "Password" field', "The password is shown masked as dots", "wrong-password-123"],
      ["Submit the form", "The sign-in attempt is refused"],
      ["Verify an error message about invalid credentials is displayed", "An error message is shown and the user stays on the sign-in page"],
    ], "An error message is displayed and the user is not signed in", [...pre, "A valid test user exists", "The user is signed out"], "Ensures sign-in fails safely with a wrong password."));
  }
  if (fields.length && !happy && !isLoginForm) out.push(c("POSITIVE", "HIGH", `Submit ${pageName} with valid data`, [
    open, ...fields.map((x) => fillStep(x)), ["Submit the form", "The form is sent"],
    ["Verify a confirmation message is shown", "A success or thank-you message appears and no error message is shown"],
  ], "The form is sent and a confirmation is shown", pre, "Happy path with realistic valid data for every field."));

  // Sentences no rule understood: kept as manual cases rather than dropped, and clearly marked.
  for (const req of unmatched.filter((s) => s.length > 12)) {
    const short = req.length > 70 ? `${req.slice(0, 67)}…` : req;
    out.push(c("FUNCTIONAL", "MEDIUM", `Manual check: ${short}`, [
      open,
      [`Perform the behaviour described: ${req}`, "Each action is accepted without errors", "Valid, realistic data for this feature"],
      ["Check the outcome on screen", "The result described in the requirement is visible to the user"],
    ], `The system satisfies the requirement: ${req}`, [...pre, "Complete these steps with exact actions and quoted UI text before automating this case"], req));
  }
  return out;
}
